/**
 * End-to-end Media3 extractor/decoder exercise against actual H264/AAC files,
 * served over a real loopback HTTP server that supports byte-range requests.
 * Fixtures are generated by FFmpeg on CI and pushed only after app install.
 *
 * Native libmpv/LibVLC are intentionally NOT declared qualified by this emulator
 * suite: their ABI, Surface and hardware-decoder paths require separate ARM tests.
 */
@RunWith(AndroidJUnit4::class)
class PlaybackDecoderFixtureInstrumentedTest {
    private val instrumentation = InstrumentationRegistry.getInstrumentation()
    private val targetContext get() = instrumentation.targetContext

    private data class Snapshot(
        val positionMs: Long,
        val durationMs: Long,
        val canSeek: Boolean,
        val isPlaying: Boolean,
        val playWhenReady: Boolean,
        val firstFrame: Boolean,
        val state: EnginePlaybackState
    )

    private fun <T> onMain(block: () -> T): T {
        var result: Any? = null
        var problem: Throwable? = null
        instrumentation.runOnMainSync {
            try {
                result = block()
            } catch (error: Throwable) {
                problem = error
            }
        }
        problem?.let { throw it }
        @Suppress("UNCHECKED_CAST")
        return result as T
    }

    private fun snapshot(engine: ExoPlayerEngine) = onMain {
        Snapshot(
            positionMs = engine.currentPositionMs,
            durationMs = engine.durationMs,
            canSeek = engine.canSeek,
            isPlaying = engine.isPlaying,
            playWhenReady = engine.playWhenReady,
            firstFrame = engine.firstFrameRendered.value,
            state = engine.playbackState.value
        )
    }

    private fun awaitState(
        engine: ExoPlayerEngine,
        description: String,
        timeoutMs: Long = 35_000L,
        predicate: (Snapshot) -> Boolean
    ): Snapshot {
        val deadline = SystemClock.elapsedRealtime() + timeoutMs
        var last = snapshot(engine)
        while (SystemClock.elapsedRealtime() < deadline) {
            last = snapshot(engine)
            if (last.state is EnginePlaybackState.Error) {
                fail("$description: decoder failed: ${last.state}")
            }
            if (predicate(last)) return last
            SystemClock.sleep(120)
        }
        fail("$description timed out, last observed: $last")
        error("unreachable")
    }

    private fun fixture(name: String): File {
        val dir = targetContext.getExternalFilesDir("decoder-fixtures")
        val file = File(dir, name)
        assertTrue("CI must push playable $name before instrumentation", file.isFile)
        assertTrue("Fixture unexpectedly empty: $name", file.length() > 2_000L)
        return file
    }

    private fun withMedia(
        name: String,
        mime: String,
        interruptInitialResponse: Boolean = false,
        action: (ExoPlayerEngine, RangeFixtureServer) -> Unit
    ) {
        RangeFixtureServer(fixture(name), interruptFirstResponse = interruptInitialResponse).use { server ->
            lateinit var engine: ExoPlayerEngine
            lateinit var surface: Surface
            lateinit var texture: SurfaceTexture
            onMain {
                texture = SurfaceTexture(10)
                surface = Surface(texture)
                engine = ExoPlayerEngine.create(targetContext)
                // Instrumentation has no foreground player Activity and the
                // system may deny/withdraw audio focus. Bypass only Media3's
                // automatic focus manager so these tests measure the real
                // extractor/decoder and our Play/Pause commands, not the
                // headless test runner's process-audio-focus policy.
                engine.player.setAudioAttributes(
                    androidx.media3.common.AudioAttributes.Builder()
                        .setUsage(androidx.media3.common.C.USAGE_MEDIA)
                        .setContentType(androidx.media3.common.C.AUDIO_CONTENT_TYPE_MOVIE)
                        .build(),
                    false
                )
                engine.attachSurface(surface)
                engine.prepare(server.url(mime))
                engine.play()
            }
            try {
                action(engine, server)
            } finally {
                onMain {
                    try {
                        engine.detachSurface()
                        engine.stop()
                        engine.release()
                    } finally {
                        surface.release()
                        texture.release()
                    }
                }
            }
        }
    }

    @Test
    fun indexedMkvSeeksNearMiddleAndNearEndWithoutResetToZero() =
        withMedia("indexed.mkv", "video/x-matroska") { engine, server ->
            awaitState(engine, "Matroska initial playback") {
                it.isPlaying && it.positionMs > 350L && it.firstFrame
            }
            assertTrue("Indexed MKV did not expose a decoder seek map", snapshot(engine).canSeek)
            onMain { engine.seekTo(6_000L) }
            val afterSeek = awaitState(engine, "Matroska middle seek") {
                it.isPlaying && it.positionMs in 5_500L..10_000L
            }
            awaitState(engine, "Matroska resumed after middle seek") {
                it.isPlaying && it.positionMs >= afterSeek.positionMs + 300L
            }
            onMain { engine.seekTo(9_000L) }
            awaitState(engine, "Matroska near-EOF seek") {
                it.isPlaying && it.positionMs in 8_500L..11_500L
            }
            assertTrue("HTTP decoder never opened fixture", server.requests.get() > 0)
        }

    @Test
    fun transportStreamDecodesAndOnlySeeksWhenDemuxerExposesASeekMap() =
        withMedia("unindexed.ts", "video/mp2t") { engine, server ->
            awaitState(engine, "MPEG-TS initial decoding") {
                it.isPlaying && it.positionMs > 350L && it.firstFrame
            }
            if (snapshot(engine).canSeek) {
                onMain { engine.seekTo(6_000L) }
                awaitState(engine, "MPEG-TS decoder-confirmed seek") {
                    it.isPlaying && it.positionMs in 5_500L..10_000L
                }
            } else {
                // Non-indexed TS is allowed to have no random seek map.
                // Do not turn duration estimation into invented seekability.
                Log.i("DecoderFixtures", "TS seek unsupported by emulator demuxer; playback verified")
                assertFalse(snapshot(engine).canSeek)
            }
            assertTrue(server.requests.get() > 0)
        }

    @Test
    fun explicitPauseSurvivesSeekAndPlaybackResumesOnPlayCommand() =
        withMedia("seek-control.mp4", "video/mp4") { engine, _ ->
            awaitState(engine, "MP4 startup") { it.isPlaying && it.positionMs > 350L }
            assertTrue(snapshot(engine).canSeek)
            onMain {
                engine.pause()
                engine.seekTo(4_000L)
            }
            awaitState(engine, "Paused seek completion") {
                it.state is EnginePlaybackState.Ready &&
                    !it.playWhenReady && !it.isPlaying &&
                    it.positionMs in 3_500L..5_500L
            }
            val pausedAt = snapshot(engine).positionMs
            SystemClock.sleep(700L)
            val pausedAfter = snapshot(engine)
            assertFalse("Seek incorrectly rearmed user Pause", pausedAfter.playWhenReady)
            assertFalse("Seek played despite user Pause", pausedAfter.isPlaying)
            assertTrue(
                "Paused decoder clock advanced unexpectedly: $pausedAt -> ${pausedAfter.positionMs}",
                pausedAfter.positionMs - pausedAt < 550L
            )
            onMain { engine.play() }
            awaitState(engine, "Playback resumes only after Play") {
                it.isPlaying && it.playWhenReady && it.positionMs > pausedAt + 350L
            }
        }

    @Test
    fun droppedInitialHttpBodyRetriesAndKeepsPlaybackIntent() =
        withMedia("indexed.mkv", "video/x-matroska", interruptInitialResponse = true) { engine, server ->
            val initial = awaitState(engine, "MKV recovers from an interrupted HTTP body") {
                it.isPlaying && it.playWhenReady && it.firstFrame && it.positionMs > 500L
            }
            assertEquals("A single controlled disconnect must be injected", 1, server.disconnectedResponses.get())
            assertTrue("Media3 did not reopen the interrupted stream", server.requests.get() >= 2)
            assertTrue("A retry must not change Play into Pause", initial.playWhenReady)

            onMain { engine.seekTo(6_000L) }
            val seeked = awaitState(engine, "Post-recovery MKV seek") {
                it.isPlaying && it.playWhenReady && it.positionMs in 5_500L..9_500L
            }
            awaitState(engine, "Post-recovery timeline progress") {
                it.isPlaying && it.positionMs > seeked.positionMs + 250L
            }
        }

    @Test
    fun fixtureServerSupportsRealRandomAccessByteRanges() {
        RangeFixtureServer(fixture("indexed.mkv")).use { server ->
            val conn = URL(server.url("video/x-matroska")).openConnection() as HttpURLConnection
            try {
                conn.setRequestProperty("Range", "bytes=128-255")
                conn.connectTimeout = 3_000
                conn.readTimeout = 3_000
                assertEquals(206, conn.responseCode)
                assertEquals(128, conn.inputStream.use { it.readBytes() }.size)
                assertTrue(server.partialRequests.get() > 0)
            } finally {
                conn.disconnect()
            }
        }
    }

    /** A tiny private HTTP origin with real 206 and 416 semantics, no network dependencies. */
    internal class RangeFixtureServer(
        private val file: File,
        private val interruptFirstResponse: Boolean = false
    ) : Closeable {
        private val listener = ServerSocket(
            0, 8, InetAddress.getByName("127.0.0.1")
        ).apply { soTimeout = 500 }
        private val active = java.util.concurrent.atomic.AtomicBoolean(true)
        val requests = AtomicInteger(0)
        val partialRequests = AtomicInteger(0)
        val disconnectedResponses = AtomicInteger(0)
        private val worker = thread(name = "bousygram-fixture-http", isDaemon = true) {
            while (active.get()) {
                try {
                    listener.accept().use { socket -> serve(socket) }
                } catch (_: java.net.SocketTimeoutException) {
                    // Poll close flag without a stuck test-worker thread.
                } catch (error: SocketException) {
                    if (active.get()) Log.e("DecoderFixtures", "Fixture socket error", error)
                    break
                } catch (error: Exception) {
                    Log.e("DecoderFixtures", "Fixture request failed", error)
                }
            }
        }

        fun url(mime: String): String =
            "http://127.0.0.1:${listener.localPort}/${file.name}?mime=$mime&name=${file.name}"

        private fun serve(socket: Socket) {
            socket.soTimeout = 7_000
            val input = BufferedReader(
                InputStreamReader(socket.getInputStream(), StandardCharsets.ISO_8859_1)
            )
            val request = input.readLine() ?: return
            var range: String? = null
            while (true) {
                val line = input.readLine() ?: return
                if (line.isEmpty()) break
                if (line.startsWith("Range:", ignoreCase = true)) {
                    range = line.substringAfter(':').trim()
                }
            }
            requests.incrementAndGet()
            val size = file.length()
            val match = range?.let { Regex("bytes=(\\d+)-(\\d*)").matchEntire(it) }
            val start = match?.groupValues?.get(1)?.toLongOrNull() ?: 0L
            val requestedEnd = match?.groupValues?.get(2)?.takeIf { it.isNotEmpty() }?.toLongOrNull()
            val out = BufferedOutputStream(socket.getOutputStream())
            if ((range != null && match == null) || start >= size) {
                out.write((
                    "HTTP/1.1 416 Range Not Satisfiable\r\n" +
                        "Content-Range: bytes */$size\r\nContent-Length: 0\r\nConnection: close\r\n\r\n"
                    ).toByteArray(StandardCharsets.ISO_8859_1))
                out.flush()
                return
            }
            val end = (requestedEnd ?: size - 1L).coerceAtMost(size - 1L)
            if (end < start) return
            val length = end - start + 1L
            val partial = range != null
            if (partial) partialRequests.incrementAndGet()
            val headers = buildString {
                append(if (partial) "HTTP/1.1 206 Partial Content\r\n" else "HTTP/1.1 200 OK\r\n")
                append("Accept-Ranges: bytes\r\n")
                append("Content-Type: application/octet-stream\r\n")
                append("Content-Length: $length\r\n")
                if (partial) append("Content-Range: bytes $start-$end/$size\r\n")
                append("Connection: close\r\n\r\n")
            }
            out.write(headers.toByteArray(StandardCharsets.ISO_8859_1))
            if (!request.startsWith("HEAD ")) {
                RandomAccessFile(file, "r").use { source ->
                    source.seek(start)
                    val buffer = ByteArray(16 * 1024)
                    // One response advertises the full Content-Length, then its
                    // body is cut short. This exercises a genuine HTTP EOF and
                    // Media3's retry/reopen path without any Telegram credentials.
                    val interruptThisBody = interruptFirstResponse &&
                        disconnectedResponses.compareAndSet(0, 1)
                    var remaining = if (interruptThisBody) minOf(length, 8L * 1024L) else length
                    while (remaining > 0L) {
                        val count = source.read(buffer, 0, minOf(buffer.size.toLong(), remaining).toInt())
                        if (count <= 0) break
                        out.write(buffer, 0, count)
                        remaining -= count
                    }
                }
            }
            out.flush()
        }

        override fun close() {
            active.set(false)
            listener.close()
            worker.join(1_500L)
        }
    }
}
